export default function Icon({
  name,
  className,
  onClick,
}: {
  name: string;
  className?: string;
  onClick?: () => void;
}) {
  function getIcon(name: string): ReactNode {
    // 首先检查自定义图标
    if (CustomIcons[name as keyof typeof CustomIcons]) {
      const CustomIcon = CustomIcons[name as keyof typeof CustomIcons];
      return <CustomIcon className={className} onClick={onClick} />;
    }

    // 从图标映射中获取图标组件
    const IconComponent = iconMap[name];
    if (IconComponent) {
      // 传递className和onClick
      return <IconComponent className={className} onClick={onClick} />;
    }

    return null;
  }

  const iconElement = getIcon(name);

  // Return null if no icon is found
  if (!iconElement) return null;

  // 直接返回图标元素
  return iconElement;
}
